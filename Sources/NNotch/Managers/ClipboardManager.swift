import AppKit
import Combine

/// Watches the system pasteboard and keeps the last 20 copied items.
/// Items can be re-copied back to the pasteboard at any time.
@MainActor
final class ClipboardManager: ObservableObject {
    /// Saklanacak öğe sayısı — kullanıcı ayarından okunur.
    var maxItems: Int { Preferences.shared.clipboardLimit }

    @Published private(set) var items: [ClipboardItem] = []

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private let imageQueue = DispatchQueue(label: "nnotch.clipboard.images", qos: .utility)
    private var capture = ClipboardCaptureState()
    private var limitObserver: AnyCancellable?
    private var tabObserver: AnyCancellable?
    private let imagesDir = Persistence.directory("ClipboardImages")

    /// Parola yöneticileri / geçici kaynaklar tarafından işaretlenen, geçmişe
    /// alınmaması gereken pano tipleri (nspasteboard.com sözleşmesi + yaygın olanlar).
    private let ignoredTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("com.apple.is-sensitive"),
    ]

    init() {
        lastChangeCount = pasteboard.changeCount
        let saved = Persistence.load([ClipboardItem].self, from: "clipboard.json") ?? []
        items = saved.map(ClipboardContent.migrated)
        if items != saved { persist() }

        // Gizlilik: pano izleme yalnızca Pano modülü açıkken çalışır. Modül
        // kapatıldığında arka planda kopyalananlar ne yakalanır ne diske yazılır.
        // ($enabledTabs abonelikte mevcut değeri hemen yayınlar → ilk kurulum da buradan.)
        tabObserver = Preferences.shared.$enabledTabs
            .map { $0.contains(IslandTab.clipboard.rawValue) }
            .removeDuplicates()
            .sink { [weak self] enabled in self?.setMonitoring(enabled) }

        // Limit ayardan düşürülünce fazlalığı hemen kırp.
        limitObserver = Preferences.shared.$clipboardLimit
            .dropFirst()
            .sink { [weak self] limit in self?.trim(to: limit) }
    }

    deinit { timer?.invalidate() }

    private func setMonitoring(_ enabled: Bool) {
        if enabled {
            guard timer == nil else { return }
            // Modül kapalıyken kopyalananlar geriye dönük yakalanmasın.
            lastChangeCount = pasteboard.changeCount
            let timer = Timer(timeInterval: 1.0, repeats: true) { [weak self] _ in
                Task { @MainActor in self?.poll() }
            }
            timer.tolerance = 0.1
            RunLoop.main.add(timer, forMode: .common)
            self.timer = timer
        } else {
            capture.invalidate()
            timer?.invalidate()
            timer = nil
        }
    }

    private func trim(to limit: Int) {
        guard items.count > limit else { return }
        while items.count > limit { cleanupStorage(for: items.removeLast()) }
        persist()
    }

    private func poll() {
        guard !capture.isProcessing else { return }
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = pasteboard.types ?? []
        guard !types.contains(where: { ignoredTypes.contains($0) }) else { return }

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            // Çoklu dosya kopyalandığında hepsini yakala (listede aynı sıra korunur).
            var seenPaths = Set<String>()
            let capturedURLs = urls.lazy.filter { seenPaths.insert($0.path).inserted }.prefix(maxItems)
            for url in Array(capturedURLs).reversed() {
                add(kind: .file, value: url.path, contentKey: "file:\(url.path)")
            }
        } else if types.contains(.tiff) || types.contains(.png) {
            if let png = pasteboard.data(forType: .png) {
                addImage(data: png, isPNG: true)
            } else if let tiff = pasteboard.data(forType: .tiff) {
                addImage(data: tiff, isPNG: false)
            }
        } else if let string = pasteboard.string(forType: .string),
                  !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            if trimmed.hasPrefix("http://") || trimmed.hasPrefix("https://"),
               !trimmed.contains(" "), URL(string: trimmed) != nil {
                add(kind: .link, value: trimmed, contentKey: ClipboardContent.key(kind: .link, value: trimmed))
            } else {
                add(kind: .text, value: string, contentKey: ClipboardContent.key(kind: .text, value: string))
            }
        }
    }

    private func addImage(data: Data, isPNG: Bool) {
        guard let token = capture.begin() else { return }
        let capturedAt = Date()
        imageQueue.async { [weak self] in
            let result: (Data, String)? = autoreleasepool {
                guard let png = ClipboardContent.pngData(from: data, isPNG: isPNG) else { return nil }
                return (png, "image:" + ClipboardContent.digest(png))
            }
            Task { @MainActor [weak self] in
                guard let self, self.capture.finish(token), let (png, key) = result else { return }
                if self.moveExistingToFront(contentKey: key) { return }
                let url = self.imagesDir.appendingPathComponent("\(UUID().uuidString).png")
                do {
                    try png.write(to: url, options: .atomic)
                } catch {
                    NSLog("Clipboard image write failed: \(error.localizedDescription)")
                    return
                }
                self.insert(ClipboardItem(id: UUID(), date: capturedAt, kind: .image, value: url.path, contentKey: key))
            }
        }
    }

    private func add(kind: ClipboardItem.Kind, value: String, contentKey: String) {
        if moveExistingToFront(contentKey: contentKey) { return }
        insert(ClipboardItem(id: UUID(), date: Date(), kind: kind, value: value, contentKey: contentKey))
    }

    private func moveExistingToFront(contentKey: String) -> Bool {
        guard let index = items.firstIndex(where: { $0.contentKey == contentKey }) else { return false }
        guard index != 0 else { return true }
        let item = items.remove(at: index)
        items.insert(item, at: 0)
        persist()
        return true
    }

    private func insert(_ item: ClipboardItem) {
        items.insert(item, at: 0)
        while items.count > maxItems {
            let removed = items.removeLast()
            cleanupStorage(for: removed)
        }
        persist()
    }

    // MARK: - Actions

    func copyToPasteboard(_ item: ClipboardItem) {
        switch item.kind {
        case .text, .link:
            pasteboard.clearContents()
            pasteboard.setString(item.value, forType: .string)
        case .file:
            pasteboard.clearContents()
            pasteboard.writeObjects([URL(fileURLWithPath: item.value) as NSURL])
        case .image:
            // Önce oku, sonra temizle: dosya okunamazsa kullanıcının mevcut
            // panosu sebepsiz yere boşaltılmasın.
            guard let image = NSImage(contentsOfFile: item.value) else { return }
            pasteboard.clearContents()
            pasteboard.writeObjects([image])
        }
        // Our own write bumps changeCount; swallow it so the item isn't re-captured,
        // but move it to the front like a fresh copy.
        capture.invalidate()
        lastChangeCount = pasteboard.changeCount
        _ = moveExistingToFront(contentKey: item.contentKey)
    }

    func remove(_ item: ClipboardItem) {
        capture.invalidate()
        items.removeAll { $0.id == item.id }
        cleanupStorage(for: item)
        persist()
    }

    func clearAll() {
        capture.invalidate()
        for item in items { cleanupStorage(for: item) }
        items.removeAll()
        persist()
    }

    private func cleanupStorage(for item: ClipboardItem) {
        if item.kind == .image {
            try? FileManager.default.removeItem(atPath: item.value)
        }
    }

    private func persist() {
        Persistence.save(items, to: "clipboard.json")
    }
}
